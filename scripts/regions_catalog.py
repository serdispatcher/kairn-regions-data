def rect_tiles(lat_range, lon_range):
    return [(la, lo) for la in lat_range for lo in lon_range]


def parse_hgt_coords(tile_names):
    coords = []
    for name in tile_names:
        stem = name[:-4] if name.endswith(".hgt") else name
        ns = 1 if stem[0] == "N" else -1
        la = ns * int(stem[1:3])
        ew = 1 if stem[3] == "E" else -1
        lo = ew * int(stem[4:7])
        coords.append((la, lo))
    return coords


